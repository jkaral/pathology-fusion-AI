"""Stage 0: cohort construction, data-quirk audit, fixed patient-level split and CV folds.

Usage:
    python scripts/00_prepare_data.py              # writes artifacts/{data,splits}/
    python scripts/00_prepare_data.py --force      # overwrite an existing split (avoid!)

Outputs (all committed):
    artifacts/data/cohort.csv          one row per patient: selected slide, label, age, sex
    artifacts/data/excluded.csv        patients that cannot be used, with the reason
    artifacts/data/data_audit.md       every quirk found and how it was handled
    artifacts/splits/split_v1.csv      patient -> train/val/test (+ .sha256)
    artifacts/splits/cv_folds_v1.csv   development-set folds for the agent (+ .sha256)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from pathfusion.config import load_config  # noqa: E402
from pathfusion.data.metadata import build_cohort, load_slides  # noqa: E402
from pathfusion.data.splits import (  # noqa: E402
    assert_no_leakage,
    make_cv_folds,
    make_split,
    split_summary,
    write_with_checksum,
)
from pathfusion.utils.logging import get_logger  # noqa: E402

log = get_logger("prepare_data")


def _md(df: pd.DataFrame) -> str:
    """Markdown table without the optional ``tabulate`` dependency."""
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(v).replace("|", "; ") for v in row.tolist()) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="overwrite an existing committed split")
    ap.add_argument("overrides", nargs="*", help="config overrides key=value")
    args = ap.parse_args()
    cfg = load_config(overrides=args.overrides)

    slides = load_slides(cfg)
    cohort, excluded, report = build_cohort(cfg)
    log.info("cohort: %d patients, excluded: %d", len(cohort), len(excluded))

    data_dir = cfg.paths.resolve("cohort_csv").parent
    data_dir.mkdir(parents=True, exist_ok=True)
    cohort.to_csv(cfg.paths.resolve("cohort_csv"), index=False)
    excluded.to_csv(data_dir / "excluded.csv", index=False)

    split_path = cfg.paths.resolve("split_csv")
    if split_path.exists() and not args.force:
        log.info("split already exists at %s, keeping it (use --force to regenerate)", split_path)
        split = pd.read_csv(split_path, dtype={"patient_id": str, "SampleNumber": str})
        if set(split["patient_id"]) != set(cohort["patient_id"]):
            raise RuntimeError("Committed split does not match the cohort; rerun with --force deliberately")
    else:
        split = make_split(cohort, cfg.split.fractions, cfg.split.seed)
        assert_no_leakage(split)
        digest = write_with_checksum(split, split_path)
        folds = make_cv_folds(split, cfg.split.cv_folds, cfg.split.cv_repeats, cfg.split.seed)
        write_with_checksum(folds, cfg.paths.resolve("cv_folds_csv"))
        log.info("wrote split %s (sha256 %s…)", split_path, digest[:12])

    summary = split_summary(split)
    print(summary.to_string())

    conflicts = cohort[cohort["label_conflict"]][["patient_id", "slide_labels", "WSI_ID", "label"]]
    meta = cohort.groupby("label").agg(
        patients=("patient_id", "size"), mean_age=("Age", "mean"),
        pct_female=("sex_code", lambda s: 100 * (1 - s.mean())),
    ).round(1).reset_index()

    audit = f"""# Data audit (generated by scripts/00_prepare_data.py)

Policies in force: `duplicate_id_policy={cfg.data.duplicate_id_policy}`,
`conflict_policy={cfg.data.conflict_policy}`, `slide_selection={cfg.data.slide_selection}`.
Rationale: see `docs/DATA_DECISIONS.md`.

## Counts
- Slides listed in metadata: {len(slides)}; distinct SampleNumber values: {slides['SampleNumber'].nunique()}
- Slides missing from the HF release: {len(report.missing_slides)}
- Bytes to download for the one-slide-per-patient subset: {cohort['size_bytes'].sum() / 1e9:.1f} GB
- Patients (after ID policy): {len(cohort) + len(excluded)}; usable: {len(cohort)}; excluded: {len(excluded)}

## Quirk 1: non-unique SampleNumber
{_md(report.duplicate_ids)}

## Quirk 2: conflicting slide labels within a patient
{_md(report.conflicting_patients)}

Resolved labels in the cohort:

{_md(conflicts)}

## Quirk 3 (found during audit): slides absent from the HF release
{_md(report.missing_slides)}

Patients with no available slide (excluded):

{_md(excluded)}

## Cohort by class (selected slides)
{_md(meta)}

## Split (patients)
{_md(summary.reset_index())}
"""
    (data_dir / "data_audit.md").write_text(audit)
    log.info("wrote %s", data_dir / "data_audit.md")


if __name__ == "__main__":
    main()
