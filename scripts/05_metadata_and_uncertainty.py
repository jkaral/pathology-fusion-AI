"""Analysis without images: metadata signal and the resolving power of the test set.

1. Descriptive statistics of age and sex by subtype over the cohort, with Kruskal-Wallis
   (age ~ subtype) and chi-square (sex ~ subtype) tests.
2. Metadata-only baseline (age + sex logistic regression) scored with the *development*
   CV folds, the same folds the agent uses. The test split is not read.
3. Test-set granularity (exact) and simulated sampling noise / minimum detectable
   difference for macro-AUROC and balanced accuracy at the real test class counts.

Usage: python scripts/05_metadata_and_uncertainty.py
Output: artifacts/analysis/{metadata.md, uncertainty.md, figures/*.png}
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy import stats  # noqa: E402

from pathfusion.agent.evaluator import CVEvaluator  # noqa: E402
from pathfusion.config import REPO_ROOT, load_config  # noqa: E402
from pathfusion.data.splits import load_cv_folds, load_split  # noqa: E402
from pathfusion.eval.plots import INK, INK_2, SERIES, _save, _style  # noqa: E402
from pathfusion.eval.uncertainty import bacc_granularity, simulate_test_noise  # noqa: E402
from pathfusion.fusion.spec import FusionSpec  # noqa: E402
from pathfusion.training.context import DataContext  # noqa: E402


def metadata_section(cfg, cohort: pd.DataFrame, out: Path) -> str:  # type: ignore[no-untyped-def]
    classes = cfg.data.classes
    tab = cohort.groupby("label").agg(
        patients=("patient_id", "size"), age_mean=("Age", "mean"), age_sd=("Age", "std"),
        age_median=("Age", "median"), pct_female=("sex_code", lambda s: 100 * (1 - s.mean())),
    ).reindex(classes).round(1)
    kw = stats.kruskal(*[cohort.loc[cohort.label == c, "Age"] for c in classes])
    ct = pd.crosstab(cohort["label"], cohort["Sex"]).reindex(classes)
    chi = stats.chi2_contingency(ct)
    insitu = cohort["label"] == "In situ"
    mw = stats.mannwhitneyu(cohort.loc[insitu, "Age"], cohort.loc[~insitu, "Age"])

    # dev-CV metadata-only baseline (no test patients loaded)
    split = load_split(cfg)
    dev_ids = set(split.loc[split["split"] != "test", "patient_id"])
    dev = cohort[cohort["patient_id"].isin(dev_ids)].reset_index(drop=True)
    ctx = DataContext.build(dev, None, classes, cfg.train)
    ev = CVEvaluator(ctx, load_cv_folds(cfg), "macro_auroc", cfg.seed)
    res = ev.evaluate(FusionSpec("meta_only"))
    acc_folds = []
    for _, _train, held in ev.splits:
        idx = [ev._pos[h] for h in held]
        y = ctx.labels(held)
        acc_folds.append(float((res.oof_probs[idx].argmax(1) == y).astype(float).mean()))

    # figures: age by subtype (dot strip + median/IQR), % female by subtype
    fig, ax = plt.subplots(figsize=(6.4, 3.4))
    _style(ax)
    rng = np.random.default_rng(0)
    for i, c in enumerate(classes):
        a = cohort.loc[cohort.label == c, "Age"].to_numpy()
        ax.scatter(a, i + rng.uniform(-0.18, 0.18, len(a)), s=10, color=SERIES[0], alpha=0.55, linewidths=0)
        q1, med, q3 = np.percentile(a, [25, 50, 75])
        ax.plot([q1, q3], [i, i], color=INK, linewidth=2, solid_capstyle="round")
        ax.plot([med], [i], "o", color=INK, markersize=5)
    ax.set_yticks(range(len(classes)), [f"{c} (n={int(tab.loc[c, 'patients'])})" for c in classes], fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("Age (years); dots = patients, bar = IQR, dot = median", fontsize=8.5, color=INK)
    _save(fig, out / "figures" / "age_by_subtype.png")

    fig, ax = plt.subplots(figsize=(6.4, 3.0))
    _style(ax)
    ax.grid(axis="y", visible=False)
    ax.barh(range(len(classes)), tab["pct_female"], color=SERIES[0], height=0.6, zorder=2)
    overall = 100 * (1 - cohort["sex_code"].mean())
    ax.axvline(overall, color=INK_2, linestyle="--", linewidth=0.8)
    for i, v in enumerate(tab["pct_female"]):
        ax.text(v + 1, i, f"{v:.0f}%", va="center", fontsize=8, color=INK_2)
    ax.set_yticks(range(len(classes)), classes, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlim(0, 100)
    ax.set_xlabel(f"% female (dashed: cohort {overall:.0f}%)", fontsize=8.5, color=INK)
    _save(fig, out / "figures" / "female_by_subtype.png")

    lines = ["# Metadata signal (generated by scripts/05_metadata_and_uncertainty.py)", "",
             f"Cohort: {len(cohort)} patients (selected slide's specimen age).", "",
             "| Subtype | Patients | Age mean ± sd | Age median | % female |", "|---|---|---|---|---|"]
    for c in classes:
        r = tab.loc[c]
        lines.append(f"| {c} | {int(r.patients)} | {r.age_mean} ± {r.age_sd} | {r.age_median:.0f} "
                     f"| {r.pct_female:.0f}% |")
    lines += [
        "", f"- Age ~ subtype, Kruskal-Wallis: H = {kw.statistic:.1f}, p = {kw.pvalue:.2g}.",
        f"- In situ vs. the rest, age (Mann-Whitney): median {cohort.loc[insitu, 'Age'].median():.0f} vs "
        f"{cohort.loc[~insitu, 'Age'].median():.0f}, p = {mw.pvalue:.2g}.",
        f"- Sex ~ subtype, chi-square: X2 = {chi.statistic:.1f}, dof = {chi.dof}, p = {chi.pvalue:.2g}.",
        "", "## Metadata-only baseline on development CV (same folds as the agent; test not used)", "",
        f"- Macro AUROC: {res.mean:.3f} ± {res.sd:.3f} (fold mean ± sd); "
        f"pooled out-of-fold {res.pooled['macro_auroc']:.3f}.",
        f"- Balanced accuracy (pooled OOF): {res.pooled['balanced_accuracy']:.3f}; chance = {1 / len(classes):.3f}.",
        f"- Accuracy per fold: {', '.join(f'{b:.2f}' for b in acc_folds)}.",
        "", "Figures: `figures/age_by_subtype.png`, `figures/female_by_subtype.png`.",
    ]
    return "\n".join(lines) + "\n"


def uncertainty_section(cfg, split: pd.DataFrame) -> str:  # type: ignore[no-untyped-def]
    classes = cfg.data.classes
    test_counts = split[split["split"] == "test"]["label"].value_counts().reindex(classes).astype(int)
    gran = bacc_granularity(test_counts.to_dict())
    lines = ["# What can a 41-patient test set resolve? (generated)", "",
             "## Exact: one test patient's effect on balanced accuracy", "",
             "| Subtype | Test patients | One patient moves balanced acc. by |", "|---|---|---|"]
    for c in classes:
        lines.append(f"| {c} | {test_counts[c]} | {100 * gran[c]:.1f} points |")
    lines += ["", "## Simulated sampling noise (latent-score model, 2000 test sets, real class counts)", "",
              "Two classifiers share patient-level noise (rho = 0.6, typical of models on the same features). "
              "MDD = minimum detectable paired difference at alpha = 0.05, power = 0.8.", "",
              "| signal A / B | AUROC A | AUROC B | SD(AUROC) | SD(ΔAUROC) | MDD AUROC | bacc A | bacc B | "
              "SD(bacc) | SD(Δbacc) | MDD bacc |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for sa, sb in ((1.0, 1.0), (1.5, 1.5), (2.0, 2.0), (2.0, 1.5)):
        n = simulate_test_noise(test_counts.tolist(), sa, sb, rho=0.6, n_sim=2000, seed=0)
        lines.append(f"| {sa} / {sb} | {n.auroc_a:.3f} | {n.auroc_b:.3f} | {n.sd_auroc:.3f} | {n.sd_diff_auroc:.3f} "
                     f"| {n.mdd_auroc:.3f} | {n.bacc_a:.3f} | {n.bacc_b:.3f} | {n.sd_bacc:.3f} | "
                     f"{n.sd_diff_bacc:.3f} | {n.mdd_bacc:.3f} |")
    lines += ["", "Reading: with equal true performance (rows 1-3) the SD of a paired difference is the noise floor. "
              "A fused-vs-single gain smaller than the MDD cannot be reliably shown on this test set, so the "
              "development-CV evidence and paired bootstrap must carry the claim."]
    return "\n".join(lines) + "\n"


def main() -> None:
    cfg = load_config()
    out = REPO_ROOT / "artifacts" / "analysis"
    (out / "figures").mkdir(parents=True, exist_ok=True)
    cohort = pd.read_csv(cfg.paths.resolve("cohort_csv"), dtype={"patient_id": str, "SampleNumber": str})
    (out / "metadata.md").write_text(metadata_section(cfg, cohort, out))
    (out / "uncertainty.md").write_text(uncertainty_section(cfg, load_split(cfg)))
    print((out / "metadata.md").read_text())
    print((out / "uncertainty.md").read_text())


if __name__ == "__main__":
    main()
