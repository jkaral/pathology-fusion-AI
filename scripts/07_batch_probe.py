"""Shortcut / batch-effect probe: could slide acquisition order leak the label?

Motivation: slide IDs are grouped by subtype, and the ID alone predicts subtype (CV macro
AUROC ~0.78). If staining/scanning batches follow ID order, image features can carry batch
information that correlates with the label without being morphology.

Development patients only (test untouched). Three probes:

1. **Stain statistics vs. ID within class.** Per slide, tissue-pixel colour statistics from
   the lossless 1.25x thumbnail (mean RGB, mean optical density per channel, saturation).
   Spearman correlation with the slide-ID rank after removing class means (partial,
   within-class). A large within-class correlation = a batch drift that follows ID order.
2. **Stain statistics -> subtype.** 5-fold CV macro AUROC of a logistic regression on the
   colour statistics alone (same folds as the agent). High values = colour is a shortcut.
3. **Foundation-model features -> ID within class.** Ridge regression from mean-pooled tile
   embeddings to the within-class-centred ID rank, CV R^2, with a label-preserving
   permutation test (IDs shuffled within class). Significant R^2 = features encode batch
   beyond subtype.

Usage:
    PATHFUSION_CONFIG=conf/pilot.yaml python scripts/07_batch_probe.py
Output: <results_dir>/../batch_probe/{batch_probe.md, stain_vs_id.png}
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from PIL import Image  # noqa: E402
from scipy import stats  # noqa: E402
from sklearn.linear_model import LogisticRegression, RidgeCV  # noqa: E402
from sklearn.metrics import roc_auc_score  # noqa: E402
from sklearn.model_selection import KFold  # noqa: E402
from sklearn.pipeline import make_pipeline  # noqa: E402
from sklearn.preprocessing import StandardScaler  # noqa: E402

from pathfusion.config import load_config  # noqa: E402
from pathfusion.data.splits import load_cv_folds, load_split  # noqa: E402
from pathfusion.embeddings.store import FeatureStore  # noqa: E402
from pathfusion.eval.plots import INK, INK_2, _save, _style  # noqa: E402

STAIN_COLS = ["mean_r", "mean_g", "mean_b", "od_r", "od_g", "od_b", "saturation", "brightness"]


def stain_stats(png: Path) -> dict[str, float]:
    a = np.asarray(Image.open(png).convert("RGBA")).astype(np.float64)
    tissue = a[..., 3] > 127
    rgb = a[..., :3][tissue] / 255.0
    od = -np.log(np.clip(rgb, 1 / 255, 1.0))
    mx, mn = rgb.max(1), rgb.min(1)
    sat = np.divide(mx - mn, mx, out=np.zeros_like(mx), where=mx > 0)
    return {"mean_r": rgb[:, 0].mean(), "mean_g": rgb[:, 1].mean(), "mean_b": rgb[:, 2].mean(),
            "od_r": od[:, 0].mean(), "od_g": od[:, 1].mean(), "od_b": od[:, 2].mean(),
            "saturation": sat.mean(), "brightness": mx.mean(), "tissue_px": float(tissue.sum())}


def within_class(x: pd.Series, labels: pd.Series) -> pd.Series:
    return x - x.groupby(labels).transform("mean")


def main() -> None:
    cfg = load_config()
    out = cfg.paths.resolve("results_dir").parent / "batch_probe"
    out.mkdir(parents=True, exist_ok=True)
    cohort = pd.read_csv(cfg.paths.resolve("cohort_csv"), dtype={"patient_id": str})
    split = load_split(cfg)
    dev_ids = set(split.loc[split["split"] != "test", "patient_id"])
    dev = cohort[cohort["patient_id"].isin(dev_ids)].copy()
    dev["wsi_num"] = dev["WSI_ID"].str[4:].astype(int)
    dev["id_rank"] = dev["wsi_num"].rank()
    thumbs = cfg.paths.resolve("qc_dir") / "thumbs"
    have = dev["WSI_ID"].map(lambda w: (thumbs / f"{w}.png").exists())
    dev = dev[have].reset_index(drop=True)
    lines = ["# Batch / shortcut probe (development patients only; generated by scripts/07_batch_probe.py)", "",
             f"Slides with thumbnails: {len(dev)} development patients.", ""]

    # 1. stain statistics vs ID, within class --------------------------------------------
    st = pd.DataFrame([stain_stats(thumbs / f"{w}.png") for w in dev["WSI_ID"]])
    dev = pd.concat([dev, st], axis=1)
    rid = within_class(dev["id_rank"], dev["label"])
    lines += ["## 1. Stain statistics vs. slide-ID rank, within class (Spearman, class means removed)", "",
              "| statistic | rho | p |", "|---|---|---|"]
    rhos = {}
    for c in STAIN_COLS:
        r, p = stats.spearmanr(within_class(dev[c], dev["label"]), rid)
        rhos[c] = (r, p)
        lines.append(f"| {c} | {r:+.3f} | {p:.2g} |")

    # 2. stain statistics -> subtype (agent folds) -----------------------------------------
    folds = load_cv_folds(cfg)
    fold_of = dict(zip(folds["patient_id"], folds["fold"]))
    dev["fold"] = dev["patient_id"].map(fold_of)
    x = dev[STAIN_COLS].to_numpy()
    y = dev["label_idx"].to_numpy()
    oof = np.zeros((len(dev), len(cfg.data.classes)))
    for k in sorted(dev["fold"].unique()):
        tr, te = dev["fold"] != k, dev["fold"] == k
        clf = make_pipeline(StandardScaler(), LogisticRegression(C=1.0, class_weight="balanced", max_iter=5000))
        clf.fit(x[tr], y[tr])
        oof[np.ix_(te.to_numpy(), clf.classes_)] = clf.predict_proba(x[te])
    present = np.unique(y)
    auc = roc_auc_score(y, oof[:, present] / oof[:, present].sum(1, keepdims=True), multi_class="ovr",
                        average="macro", labels=present)
    lines += ["", "## 2. Stain statistics alone -> subtype (5-fold CV, agent folds)", "",
              f"- Macro AUROC: **{auc:.3f}** (for reference: age+sex 0.588, slide ID alone 0.778)."]

    # 3. FM features -> ID within class --------------------------------------------------
    emb_dir = cfg.paths.resolve("embeddings_dir")
    avail = dev["WSI_ID"].map(lambda w: (emb_dir / f"{w}.h5").exists())
    sub = dev[avail].reset_index(drop=True)
    if len(sub) >= 30:
        store = FeatureStore.from_dir(emb_dir, sub, cfg.extract.models)
        target = within_class(sub["id_rank"], sub["label"]).to_numpy()
        lines += ["", "## 3. Mean-pooled FM features -> within-class slide-ID rank (ridge, 5-fold CV R², "
                  "200 within-class permutations)", "", "| model | CV R² | permutation p |", "|---|---|---|"]
        rng = np.random.default_rng(0)
        for m in cfg.extract.models:
            feats = np.stack([store.bag(m, p).float().mean(0).numpy() for p in sub["patient_id"]])

            def cv_r2(t: np.ndarray, feats: np.ndarray = feats) -> float:
                pred = np.zeros_like(t)
                for tr, te in KFold(5, shuffle=True, random_state=0).split(feats):
                    reg = make_pipeline(StandardScaler(), RidgeCV(alphas=np.logspace(0, 4, 9)))
                    pred[te] = reg.fit(feats[tr], t[tr]).predict(feats[te])
                return float(1 - ((t - pred) ** 2).sum() / ((t - t.mean()) ** 2).sum())

            r2 = cv_r2(target)
            null = []
            for _ in range(200):
                perm = target.copy()
                for lab in sub["label"].unique():
                    idx = np.flatnonzero(sub["label"].to_numpy() == lab)
                    perm[idx] = rng.permutation(perm[idx])
                null.append(cv_r2(perm))
            p = (1 + np.sum(np.array(null) >= r2)) / (1 + len(null))
            lines.append(f"| {m} | {r2:+.3f} | {p:.3f} |")
    else:
        lines += ["", f"## 3. skipped: only {len(sub)} slides with features"]

    # figure: strongest stain statistic vs ID ----------------------------------------------
    best = max(rhos, key=lambda c: abs(rhos[c][0]))
    fig, ax = plt.subplots(figsize=(6.4, 3.4))
    _style(ax)
    ax.scatter(dev["wsi_num"], dev[best], s=12, color="#2a78d6", alpha=0.7, linewidths=0)
    ax.set_xlabel("slide ID number (WSI-n)", fontsize=8.5, color=INK)
    ax.set_ylabel(best, fontsize=8.5, color=INK)
    ax.set_title(f"{best} vs slide ID (within-class Spearman {rhos[best][0]:+.2f})", fontsize=9, color=INK_2,
                 loc="left")
    _save(fig, out / "stain_vs_id.png")
    lines += ["", "Figure: `stain_vs_id.png` (strongest within-class stain statistic).", "",
              "Interpretation guide: probe 2 near the slide-ID AUROC, or a significant probe 3, means batch "
              "signal is available to the classifier; mitigations are stain normalisation / colour augmentation "
              "at tiling time, or reporting performance within acquisition batches."]
    (out / "batch_probe.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
