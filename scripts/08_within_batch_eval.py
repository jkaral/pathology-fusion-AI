"""Does the classifier still discriminate subtypes *within* an acquisition block?

Slide IDs are grouped by subtype and the image features encode ID position (see
``07_batch_probe.py``), so part of the cross-validated AUROC could come from recognising the
acquisition batch rather than morphology. A batch signature cannot separate classes that
were acquired together, so this script re-scores the agent's out-of-fold (OOF)
predictions **within ID blocks**. For every block it takes the classes with at least
``--min-per-class`` patients, renormalises the OOF probabilities over those classes, and
computes macro OvR AUROC on that block alone.

Compared side by side:
* each agent trial's model (e.g. the selected fusion, the single-model references),
* an *ID-only* classifier (random forest on the slide number, same CV folds), which by
  construction can only exploit ID order.

If the image models keep high within-block AUROC while ID-only drops toward 0.5, their
signal is not just batch.

Development patients only (agent OOF predictions); test is never read.

Usage:
    PATHFUSION_CONFIG=conf/pilot.yaml python scripts/08_within_batch_eval.py --run pilot_qwen3b
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from sklearn.ensemble import RandomForestClassifier  # noqa: E402
from sklearn.metrics import roc_auc_score  # noqa: E402

from pathfusion.config import load_config  # noqa: E402
from pathfusion.data.splits import load_cv_folds  # noqa: E402

BLOCKS = [(1, 100), (101, 200), (201, 300), (301, 342), (343, 410)]


def block_auroc(y: np.ndarray, probs: np.ndarray, classes: list[int]) -> float:
    keep = np.isin(y, classes)
    p = probs[keep][:, classes]
    p = p / np.clip(p.sum(1, keepdims=True), 1e-12, None)
    yy = np.searchsorted(classes, y[keep])
    if len(classes) == 2:
        return float(roc_auc_score(yy, p[:, 1]))
    return float(roc_auc_score(yy, p, multi_class="ovr", average="macro", labels=list(range(len(classes)))))


def id_only_oof(dev: pd.DataFrame, folds: pd.DataFrame, n_classes: int) -> np.ndarray:
    oof = np.zeros((len(dev), n_classes))
    pos = {p: i for i, p in enumerate(dev["patient_id"])}
    for _, grp in folds.groupby("fold"):
        held = set(grp["patient_id"])
        tr = dev[~dev["patient_id"].isin(held)]
        te = dev[dev["patient_id"].isin(held)]
        rf = RandomForestClassifier(300, min_samples_leaf=3, random_state=0).fit(tr[["wsi_num"]], tr["label_idx"])
        oof[np.ix_([pos[p] for p in te["patient_id"]], rf.classes_)] = rf.predict_proba(te[["wsi_num"]])
    return oof


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True, help="agent run id under paths.agent_dir")
    ap.add_argument("--min-per-class", type=int, default=3)
    args = ap.parse_args()
    cfg = load_config()
    run_dir = cfg.paths.resolve("agent_dir") / args.run
    z = np.load(run_dir / "oof_probs.npz")
    dev_ids = [str(x) for x in z["dev_ids"]]
    cohort = pd.read_csv(cfg.paths.resolve("cohort_csv"), dtype={"patient_id": str}).set_index("patient_id")
    dev = cohort.loc[dev_ids].reset_index()
    dev["wsi_num"] = dev["WSI_ID"].str[4:].astype(int)
    y = dev["label_idx"].to_numpy()
    classes = cfg.data.classes
    folds = load_cv_folds(cfg)
    lines_jsonl = (run_dir / "decisions.jsonl").read_text().splitlines()
    records = {r["index"]: r for r in (json.loads(line) for line in lines_jsonl)}
    sel = json.loads((run_dir / "selected.json").read_text())

    models: dict[str, np.ndarray] = {"ID-only (slide number)": id_only_oof(dev, folds, len(classes))}
    for idx in [r["index"] for r in records.values() if r["phase"] == "reference"] + [sel["selected_index"]]:
        label = records[idx]["config_short"] + (" [selected]" if idx == sel["selected_index"] else "")
        models[label] = z[f"trial_{idx}"]

    lines = ["# Within-acquisition-block evaluation (development OOF; generated by scripts/08_within_batch_eval.py)",
             "", f"Agent run: `{args.run}`. Blocks are slide-ID ranges; only classes with >= {args.min_per_class} "
             "patients in a block are scored, with probabilities renormalised over them.", ""]
    header = "| model | " + " | ".join(f"WSI {a}-{b}" for a, b in BLOCKS) + " | mean |"
    lines += [header, "|---|" + "---|" * (len(BLOCKS) + 1)]
    block_defs = []
    for a, b in BLOCKS:
        m = (dev["wsi_num"] >= a) & (dev["wsi_num"] <= b)
        counts = pd.Series(y[m.to_numpy()]).value_counts()
        cls = sorted(int(c) for c, n in counts.items() if n >= args.min_per_class)
        block_defs.append((m.to_numpy(), cls))
    for name, probs in models.items():
        vals = []
        for m, cls in block_defs:
            vals.append(block_auroc(y[m], probs[m], cls) if len(cls) >= 2 else float("nan"))
        cells = " | ".join("n/a" if np.isnan(v) else f"{v:.3f}" for v in vals)
        lines.append(f"| {name} | {cells} | {np.nanmean(vals):.3f} |")
    lines += ["", "Classes scored per block:"]
    for (a, b), (m, cls) in zip(BLOCKS, block_defs):
        lines.append(f"- WSI {a}-{b}: {int(m.sum())} patients; " + (", ".join(classes[c] for c in cls) or "none"))
    out = cfg.paths.resolve("results_dir").parent / "within_batch"
    out.mkdir(parents=True, exist_ok=True)
    (out / "within_batch.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
