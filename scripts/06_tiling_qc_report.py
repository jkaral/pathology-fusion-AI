"""Tiling statistics and a QC contact sheet from an extraction run (real slides).

Reads ``extraction_manifest.csv`` (written by stage 1) and the per-slide QC overlays, and
writes:
* ``tiling_report.md``: slide sizes at 20x, tissue-tile counts by subtype, how many slides
  a given ``max_tiles`` cap would truncate, and decode/encode timings with a Kaggle runtime
  projection;
* ``qc_contact_sheet_<k>.jpg``: thumbnails of every slide's tissue mask / tile grid, for
  quick human review (green = tissue outline, blue = kept tiles).

Usage:
    python scripts/06_tiling_qc_report.py --embeddings-dir artifacts/embeddings_pilot \\
        --qc-dir artifacts/qc --out artifacts/pilot/tiling
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

from pathfusion.config import load_config  # noqa: E402


def contact_sheets(qc_dir: Path, slides: list[str], labels: dict[str, str], out: Path,
                   per_sheet: int = 48, cols: int = 8, cell: int = 220) -> list[Path]:
    paths = []
    for k in range(0, len(slides), per_sheet):
        chunk = slides[k:k + per_sheet]
        rows = -(-len(chunk) // cols)
        sheet = Image.new("RGB", (cols * cell, rows * (cell + 18)), (252, 252, 251))
        draw = ImageDraw.Draw(sheet)
        for i, wsi in enumerate(chunk):
            p = qc_dir / f"{wsi}.jpg"
            if not p.exists():
                continue
            im = Image.open(p).convert("RGB")
            im.thumbnail((cell - 6, cell - 6))
            x, y = (i % cols) * cell, (i // cols) * (cell + 18)
            sheet.paste(im, (x + 3, y + 3))
            draw.text((x + 4, y + cell), f"{wsi} {labels.get(wsi, '')}", fill=(40, 40, 40))
        path = out / f"qc_contact_sheet_{k // per_sheet + 1}.jpg"
        sheet.save(path, quality=80)
        paths.append(path)
    return paths


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--embeddings-dir", type=Path, required=True)
    ap.add_argument("--qc-dir", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    cfg = load_config()
    args.out.mkdir(parents=True, exist_ok=True)
    cohort = pd.read_csv(cfg.paths.resolve("cohort_csv"), dtype={"patient_id": str})
    man = pd.read_csv(args.embeddings_dir / "extraction_manifest.csv").drop_duplicates("WSI_ID", keep="last")
    df = man.merge(cohort[["WSI_ID", "label", "size_bytes"]], on="WSI_ID", how="left")
    enc_cols = [c for c in df.columns if c.endswith("_s") and c not in ("download_s", "decode_s", "tiling_s")]

    t = df["n_tissue_tiles"]
    caps = [256, 1024, 2048, 4096, 8192]
    by = df.groupby("label")["n_tissue_tiles"].describe()[["count", "min", "50%", "max"]].round(0)
    by = by.reindex([c for c in cfg.data.classes if c in by.index])  # partial runs may lack a class
    per_tile = {c[:-2]: (df[c].sum() / df["n_tiles"].sum()) for c in enc_cols}
    lines = [
        "# Tiling report (real slides; generated by scripts/06_tiling_qc_report.py)", "",
        f"Slides processed: {len(df)} / {len(cohort)}.", "",
        "## Slide size at 20x and tissue tiles (224 px, stride 224, >= 50% tissue)", "",
        f"- Width x height at 20x: median {df['width_20x'].median():.0f} x {df['height_20x'].median():.0f} px "
        f"(max {df['width_20x'].max()} x {df['height_20x'].max()}).",
        f"- Tissue tiles per slide: median {t.median():.0f}, IQR {t.quantile(.25):.0f}-{t.quantile(.75):.0f}, "
        f"range {t.min()}-{t.max()}.",
        "- Slides truncated by a max_tiles cap: " + ", ".join(f"{c}: {(t > c).mean():.0%}" for c in caps) + ".",
        "", "| Subtype | Slides | Min | Median | Max |", "|---|---|---|---|---|",
    ]
    for c, r in by.iterrows():
        lines.append(f"| {c} | {int(r['count'])} | {int(r['min'])} | {int(r['50%'])} | {int(r['max'])} |")
    lines += [
        "", "## Timing (this run)", "",
        f"- Download: median {df['download_s'].median():.1f} s/slide; decode at 20x: median "
        f"{df['decode_s'].median():.1f} s; tissue mask + grid: median {df['tiling_s'].median():.1f} s.",
        "- Encoder time per tile on this hardware: " + ", ".join(f"{k} {1000 * v:.0f} ms" for k, v in per_tile.items())
        + ".",
        "",
        "## Projection for the headline run (Kaggle 2x T4, cap 4096)", "",
        f"- Tiles to embed with cap 4096: {int(np.minimum(t, 4096).sum()):,} (vs {int(np.minimum(t, 256).sum()):,} "
        "in this pilot).",
        f"- CPU-side decode for 203 slides: ~{df['decode_s'].median() * 203 / 3600:.1f} h, overlapped with encoding by "
        "the decode-ahead thread.",
        "- GPU encode time depends on T4 throughput (not measurable here); "
        "the stage-1 notebook prints per-model tiles/s after the 2-slide smoke test, "
        "and `--summarize` totals them.",
    ]
    sheets = contact_sheets(args.qc_dir, sorted(df["WSI_ID"], key=lambda s: int(s.split("-")[1])),
                            dict(zip(df["WSI_ID"], df["label"])), args.out)
    lines += ["", "## QC contact sheets", ""] + [f"- `{p.name}`" for p in sheets]
    (args.out / "tiling_report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
